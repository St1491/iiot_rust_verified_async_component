#[derive(Clone,Copy,Debug)]
pub struct Config{
    actors_number: u32,
    numbers_of_retry: u32,
    wait_before_retry: u32, //in seconds
    shared_resources: u32,
    process_duration: u32, //in seconds
}
impl Config{
    ///Create a Config item with the passed parameters
    #[ensures(seq!(actors_number, numbers_of_retry, wait_before_retry, shared_resources, process_duration) == result@)]
    pub fn new(actors_number: u32, numbers_of_retry: u32, wait_before_retry: u32, shared_resources: u32, process_duration: u32,)->Config{
        Config{
            actors_number,
            numbers_of_retry,
            wait_before_retry,
            shared_resources,
            process_duration,
        }
        
    }
    ///Parse a vector of number (passed as string) and override the default parameters in order
    /// Return Ok if there are at most 6 arguments in the vector and all of the elements (first excluded) are int
    /// Return Error if the parsing of the number fails or there are too many arguments
    #[trusted]
    pub fn parse(args:Vec<String>)->Result<Config,Box<dyn Error>>{
        let mut params: Vec<u32> = vec![1,5,1,1,3]; //default
        if args.len()>(params.len()+1){
            return Err(Box::new(io::Error::new(io::ErrorKind::InvalidInput,"Too many arguments")))
        } 
        for i in 1..args.len(){
            params[i-1] = args[i].parse::<u32>()?;
        }
        Ok(Config::new(params[0],params[1],params[2],params[3],params[4]))
    }     

}
#[cfg(not(creusot))]
impl PartialEq for Config{
    fn eq(&self, other: &Self) -> bool {
        if self.actors_number != other.actors_number {return false;}
        if self.numbers_of_retry != other.numbers_of_retry {return false;}
        if self.wait_before_retry != other.wait_before_retry {return false;}
        if self.shared_resources != other.shared_resources {return false;}
        if self.process_duration != other.process_duration {return false;}
        return true;
    }
}
#[cfg(creusot)]
impl View for Config{
    type ViewTy = Seq<u32>;

    #[logic]
    fn view(self)->Self::ViewTy{
        pearlite!{
            seq!(self.actors_number,self.numbers_of_retry,self.wait_before_retry,self.shared_resources,self.process_duration)
        }
    }
}

///Example of how a chosen number of actors can act using a certain chosen number of shared resource 
#[cfg(not(creusot))]
pub fn run(config:Config){  
    let sr = Arc::new(Mutex::new(config.shared_resources));            //generate a number of shared resources locked via Mutex to avoid race conditions
    trpl::block_on(async {
        let mut futures  = vec![];                   //prepare an empty vector to collect the futures generated by the actors
        for i in 0..config.actors_number{                                                                  //Spawns a new simulation for each actors_number     
            futures.push(Box::pin(run_one(i.to_string(),Arc::clone(&sr),config)));     //And adds its Future output to the futures vector
        }
        let results = trpl::join_all(futures).await;                      //Await for each future and resolves all eventual errors
        for i in results{
            if let Err(e) = i{
                let a = e.downcast::<io::Error>().unwrap();
                match a.kind() {
                    io::ErrorKind::TimedOut => println!("TimedOut: {}",a),
                    io::ErrorKind::Unsupported => println!("Unsupported: {}",a),
                    _ => panic!("Error: {}",a),
                }
            }
        }       
    });
    let n = sr.lock().unwrap();
    assert_eq!(*n,config.shared_resources, "Invalid access to the shared resource, got {}, expected {}",*n, config.shared_resources);
}

#[cfg(not(creusot))]
pub fn direct_simulation(){
    let mut id = 1;
    let mut state = 0;
    let mut actor: Option<Actor<Idle>> = Some(Actor::new(id.to_string()));
    let mut init: Option<Actor<Initialized>> = None;
    let mut acting: Option<Actor<Acting>> = None;
    let mut broken: Option<Actor<Broken>> = None;
    let mut choice = String::new();
    loop{
        let display = match state {
            0 => actor.as_ref().map(|a| a.to_string()).unwrap_or_default(),
            1 => init.as_ref().map(|a| a.to_string()).unwrap_or_default(),
            2 => acting.as_ref().map(|a| a.to_string()).unwrap_or_default(),
            3 => broken.as_ref().map(|a| a.to_string()).unwrap_or_default(),
            _ => panic!("Invalid state index"),
        };

        println!(
            "{}\n1 - Check actor integrity\n2 - Start the actor\n3 - Stop the actor\n4 - New Actor\n5 - Exit",
            display
        );
        io::stdin()
        .read_line(&mut choice)
        .expect("Failed to read line");
        if let Ok(number_chosen) = choice.strip_suffix("\n").unwrap().parse::<u8>(){
            println!("{}",number_chosen);
            match number_chosen {
                1 => {
                    if state == 0{
                        match actor.clone().unwrap().check_integrity(debug_check()){
                            Ok(i) =>{
                                init = Some(i);
                                state = 1;
                            }
                            Err(b) =>{
                                broken = Some(b);
                                state = 3;
                            }
                        }
                    }
                    else {
                        println!("Unsupported transition. Only Idle actors can be checked")
                    }
                },
                2 => {
                    if state == 1{
                        acting = Some(init.clone().unwrap().act());
                        state = 2;
                    }
                    else {
                        println!("Unsupported transition: Only Initialized actors can act")
                    }
                }
                3 => {
                    if state == 2{
                        init = Some(acting.clone().unwrap().stop());
                        state = 1;
                    }
                    else {
                        println!("Unsupported transition: Only Acting actors can stop")
                    }
                }
                4 => {
                    id +=1;
                    actor = Some(Actor::new(id.to_string()));
                    state = 0;
                    println!("New actor:")
                }
                5 => {
                    break;
                }
                _ =>{
                    println!("Unrecognized input. Try again.");
                }
            }
        }
        else {
            println!("Unrecognized input. Try again.");
        }
        choice.clear();
    }
}


