#[cfg(creusot)]
mod creusot_test{
    use creusot_std::{logic::Seq, macros::{ensures, logic}};
    use super::*;


    #[trusted]
    #[requires(x@<u32::MAX@)]
    #[ensures(result@ == x@)]
    fn check_parse_creusot(x: u32) -> u32{
        let s = x.to_string();
        let v = creusot_std::vec!("Test_Creusot".to_string(),s);
        return Config::parse(v).unwrap().actors_number;
    }

    #[logic]
    pub fn compare_config(config: Result<Config,Box<dyn Error>>, args: Seq<String>) -> bool{ 
        match config{
            Ok(c) =>{
                pearlite!{
                    forall<i: Int> i >= 1 && (i < args.len() && i < (c@.len()-1)) ==> c@[i-1]@ == (args[i]@[0] as u32)@
                }
            },
            Err(_) => false,
        }
        
    }
    
}

